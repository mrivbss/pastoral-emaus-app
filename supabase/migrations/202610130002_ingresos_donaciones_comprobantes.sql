-- Control financiero de ingresos/egresos y donaciones tangibles.

alter table public.donaciones
  add column es_monetaria boolean not null default true,
  add column detalle_tangible text;

alter table public.donaciones
  drop constraint donaciones_monto_check;

alter table public.donaciones
  add constraint donaciones_monto_check check (
    (es_monetaria = true and monto > 0)
    or (
      es_monetaria = false
      and monto = 0
      and char_length(trim(coalesce(detalle_tangible, ''))) between 2 and 500
    )
  );

create table public.ingresos (
  id uuid primary key default gen_random_uuid(),
  folio bigint generated by default as identity unique,
  fecha date not null default current_date,
  tipo text not null default 'Ingreso' check (tipo in ('Ingreso', 'Egreso')),
  codigo_concepto smallint not null,
  concepto text not null,
  detalle_responsable text not null,
  comprobante text,
  observacion text,
  precio_unitario integer not null check (precio_unitario >= 0),
  cantidad integer not null default 1 check (cantidad >= 1),
  monto_total integer generated always as (precio_unitario * cantidad) stored,
  registrado_por uuid default auth.uid() references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint ingresos_codigo_tipo_check check (
    (tipo = 'Ingreso' and codigo_concepto between 1 and 9)
    or (tipo = 'Egreso' and codigo_concepto between 10 and 24)
  ),
  constraint ingresos_concepto_length check (char_length(trim(concepto)) between 2 and 160),
  constraint ingresos_detalle_length check (char_length(trim(detalle_responsable)) between 2 and 500),
  constraint ingresos_comprobante_length check (comprobante is null or char_length(comprobante) <= 200),
  constraint ingresos_observacion_length check (observacion is null or char_length(observacion) <= 1000)
);

create index ingresos_fecha_folio_idx on public.ingresos (fecha desc, folio desc);
create index ingresos_tipo_codigo_idx on public.ingresos (tipo, codigo_concepto);
create index ingresos_registrado_por_idx on public.ingresos (registrado_por)
where registrado_por is not null;

create trigger ingresos_set_updated_at
before update on public.ingresos
for each row execute function public.set_updated_at();

alter table public.ingresos enable row level security;

create policy ingresos_admin_all
on public.ingresos
for all
to authenticated
using ((select public.es_administrador()))
with check ((select public.es_administrador()));

revoke all on table public.ingresos from public, anon, authenticated;
grant select, insert, update, delete on table public.ingresos to authenticated;
grant usage, select on sequence public.ingresos_folio_seq to authenticated;

comment on table public.ingresos
is 'Movimientos financieros de Emaús, basados en el catálogo oficial de conceptos 1 al 24.';
